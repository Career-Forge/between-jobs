# ═══ 4. architecture: pure, sync, no I/O ═════════════════════════════════

_FORBIDDEN_ROOTS = {
    "httpx", "openai", "supabase", "requests", "aiohttp", "urllib3", "socket", "ssl",
    "asyncio", "asyncpg", "fastapi", "starlette", "anthropic", "litellm", "subprocess",
    "http", "sqlalchemy", "psycopg", "psycopg2", "smtplib", "ftplib", "shutil", "os",
}  # fmt: skip


def _module_tree() -> ast.Module:
    return ast.parse(_MODULE_PATH.read_text(encoding="utf-8"))


def _imports() -> set[str]:
    names: set[str] = set()
    for node in ast.walk(_module_tree()):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            names.add("." * node.level + (node.module or ""))
    return names


def test_module_directly_imports_nothing_that_can_do_io() -> None:
    # DIRECT imports only: the transitive picture is the next test's job
    imports = _imports()
    absolute = {n for n in imports if not n.startswith(".")}
    assert not {n.split(".")[0] for n in absolute} & _FORBIDDEN_ROOTS
    assert "urllib.request" not in absolute and "urllib" not in absolute
    # the only internal dependencies are the two deliberate reuses
    assert {n for n in imports if n.startswith(".")} == {".company_tiers", ".search_aggregation"}
    assert absolute == {
        "__future__",
        "re",
        "collections.abc",
        "dataclasses",
        "datetime",
        "enum",
        "typing",
        "urllib.parse",
    }


_TRANSITIVE_ALLOWLIST = {
    "httpx", "postgrest", "realtime", "ssl", "storage3", "supabase", "supabase_auth",
    "supabase_functions", "websockets",
}  # fmt: skip
"""What importing the module loads as a side effect of reusing `company_tiers` and
`search_aggregation`: the Supabase client family and the TLS/websocket pieces it needs.
Loaded, never called."""
_NETWORK_STACK_ROOTS = {
    *_TRANSITIVE_ALLOWLIST, "requests", "aiohttp", "urllib3", "openai", "anthropic", "litellm",
    "asyncpg", "psycopg", "psycopg2", "sqlalchemy", "fastapi", "starlette", "smtplib", "ftplib",
}  # fmt: skip

_IMPORT_PROBE = """
import socket, sys
before = set(sys.modules)

def boom(*args, **kwargs):
    raise AssertionError("network used while importing")

socket.socket.connect = boom
socket.create_connection = boom
socket.getaddrinfo = boom
import between_jobs.api.hiring_signals as module

module.parse_hit(module.RawSearchHit("https://example.com/", "t", "s"))
roots = {name.split(".")[0] for name in set(sys.modules) - before}
print(sorted(roots))
"""


def test_importing_the_module_opens_no_connection_even_through_its_dependencies() -> None:
    result = subprocess.run(
        [sys.executable, "-c", _IMPORT_PROBE], capture_output=True, text=True, timeout=120
    )
    assert result.returncode == 0, result.stderr[-800:]
    loaded = set(ast.literal_eval(result.stdout.strip().splitlines()[-1]))
    # an import-time client, session or LLM SDK arriving through a dependency fails here,
    # with sockets blocked above as the backstop
    assert not (loaded & _NETWORK_STACK_ROOTS) - _TRANSITIVE_ALLOWLIST, (
        loaded & _NETWORK_STACK_ROOTS
    )
    assert {
        "httpx",
        "supabase",
    } <= loaded  # the transitive load is real, so the allowlist is honest


def test_module_is_synchronous_and_never_touches_the_network_or_filesystem() -> None:
    tree = _module_tree()
    assert not any(isinstance(n, ast.AsyncFunctionDef | ast.Await) for n in ast.walk(tree))
    called = {
        n.func.id
        for n in ast.walk(tree)
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
    }
    assert not called & {"open", "eval", "exec", "__import__", "compile", "input"}
    called_attrs = {
        n.func.attr
        for n in ast.walk(tree)
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
    }
    assert not called_attrs & {"urlopen", "request", "get", "post", "fetch", "connect", "read_text"}


