def _load_pulls() -> dict[str, list[RawSearchHit]]:
    data = json.loads(_FIXTURE.read_text(encoding="utf-8"))
    return {
        pull["pull_id"]: [RawSearchHit(h["url"], h["title"], h["snippet"]) for h in pull["hits"]]
        for pull in data["pulls"]
    }


PULLS = _load_pulls()
ALL_HITS = [hit for hits in PULLS.values() for hit in hits]


def _hit(pull: str, activity_id: str, occurrence: int = 0) -> RawSearchHit:
    matches = [h for h in PULLS[pull] if f"activity-{activity_id}-" in h.url]
    return matches[occurrence]


def _signal(pull: str, activity_id: str, occurrence: int = 0) -> HiringSignal:
    parsed = parse_hit(_hit(pull, activity_id, occurrence))
    assert isinstance(parsed, HiringSignal), parsed
    return parsed


