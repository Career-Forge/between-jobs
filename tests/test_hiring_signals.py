# ═══ 2. synthetic: posted_at from the activity id ════════════════════════


def _id_for(moment: datetime, low_bits: int = 4321) -> str:
    """An activity id built the way LinkedIn builds them: time in
    milliseconds, shifted left 22 bits, with the low bits filled."""
    return str((round(moment.timestamp() * 1000) << 22) | low_bits)


def test_posted_at_is_decoded_from_the_activity_id() -> None:
    moment = datetime(2026, 9, 17, 18, 11, 20, 250_000, tzinfo=UTC)
    assert posted_at_from_activity_id(_id_for(moment)) == moment
    assert posted_at_from_activity_id(_id_for(moment, low_bits=0)) == moment
    # a hand-computed anchor: 1_700_000_000_000 ms is 2023-11-14T22:13:20Z
    assert posted_at_from_activity_id(str(1_700_000_000_000 << 22)) == datetime(
        2023, 11, 14, 22, 13, 20, tzinfo=UTC
    )


def test_posted_at_is_timezone_aware_utc() -> None:
    decoded = posted_at_from_activity_id(_id_for(datetime(2024, 1, 2, 3, 4, 5, tzinfo=UTC)))
    assert decoded is not None and decoded.tzinfo is UTC


def test_posted_at_plausibility_band_is_a_fixed_calendar_range_not_the_clock() -> None:
    first = datetime(2003, 1, 1, tzinfo=UTC)
    last = datetime(2100, 1, 1, tzinfo=UTC)
    first_ms = int(first.timestamp() * 1000)
    last_ms = int(last.timestamp() * 1000)
    assert posted_at_from_activity_id(str(first_ms << 22)) == first
    assert posted_at_from_activity_id(str((first_ms - 1) << 22)) is None
    assert posted_at_from_activity_id(str(last_ms << 22)) == last
    assert posted_at_from_activity_id(str((last_ms + 1) << 22)) is None


