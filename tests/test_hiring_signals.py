def _padded_query(target_chars: int) -> str:
    """A tab-path query that is exactly `target_chars` long, built by growing the metro."""
    roles = ["r" * 50, "s" * 50, "t" * 50, "u" * 50]
    base = build_query(
        role_terms=roles, locale=Locale.GLOBAL, freshness=Freshness.DAY, metro="m"
    ).query
    metro = "m" * (1 + target_chars - len(base))
    query = build_query(
        role_terms=roles, locale=Locale.GLOBAL, freshness=Freshness.DAY, metro=metro
    ).query
    assert len(query) == target_chars
    return query


