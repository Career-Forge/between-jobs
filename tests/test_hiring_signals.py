def test_fixture_size_and_shape() -> None:
    assert len(ALL_HITS) == 98
    assert len({h.url for h in ALL_HITS}) == 97  # one real post appears in two pulls, verbatim
    assert all(isinstance(h.title, str) and isinstance(h.snippet, str) for h in ALL_HITS)


def test_every_hit_parses_or_is_rejected_for_a_documented_reason() -> None:
    rejected: Counter[str] = Counter()
    parsed = 0
    for hit in ALL_HITS:
        result = parse_hit(hit)
        if isinstance(result, RejectedHit):
            assert result.reason in _DOCUMENTED_REASONS
            # a loggable prefix of the input: no query, fragment or token
            assert hit.url.startswith(result.url) and len(result.url) <= 200
            assert all(token not in result.url for token in ("?", "#", "rcm="))
            rejected[result.reason] += 1
        else:
            parsed += 1
    # 2 instagram, 3 ugcPost, 2 linkedin jobs pages -- read off the fixture urls by eye.
    assert rejected == {"not_linkedin": 2, "unsupported_urn": 3, "not_a_post_url": 2}
    assert parsed == 98 - 7


def test_every_parsed_activity_id_is_ascii_digits_and_embed_url_round_trips() -> None:
    for hit in ALL_HITS:
        result = parse_hit(hit)
        if isinstance(result, RejectedHit):
            continue
        assert re.fullmatch(r"[0-9]{15,25}", result.activity_id)
        assert result.activity_id.isascii()
        assert f"activity-{result.activity_id}-" in hit.url
        url = embed_url(result.activity_id)
        assert (
            url
            == f"https://www.linkedin.com/embed/feed/update/urn:li:activity:{result.activity_id}"
        )
        assert url.endswith(result.activity_id)


def test_post_url_never_carries_a_query_string_or_fragment() -> None:
    for hit in ALL_HITS:
        result = parse_hit(hit)
        if isinstance(result, HiringSignal):
            assert "?" not in result.post_url and "#" not in result.post_url
            assert "rcm=" not in result.post_url
            assert result.post_url.startswith("https://")
            assert result.activity_id in result.post_url


