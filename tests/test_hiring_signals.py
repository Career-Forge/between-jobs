def test_fixture_contains_no_contact_details_or_profile_urls() -> None:
    text = _FIXTURE.read_text(encoding="utf-8")
    # every email-shaped token is an example.com placeholder; the one other "@" is a headline
    assert set(re.findall(r"[\w.+-]+@([\w.-]+)", text)) == {"example.com"}
    assert text.count("@") == text.count("@example.com") + text.count("@ Example Institute")
    assert "linkedin.com/in/" not in text
    for needle in ("wa.me", "bit.ly", "lnkd.in", "whatsapp.com", "t.me/"):
        assert needle not in text
    # the only member-tracking token left is the clearly synthetic placeholder
    assert re.findall(r"rcm=([A-Za-z0-9]+)", text) == ["ACoAAEXAMPLE0000000000000000000000000"]


_HYGIENE_FILES = (_FIXTURE, _FIXTURE.with_name("README.md"), _MODULE_PATH, Path(__file__))
_SYNTHETIC_PROFILE_HANDLES = {"janedoe"}


@pytest.mark.parametrize("path", _HYGIENE_FILES, ids=lambda p: p.name)
def test_no_contact_details_or_real_profile_links_in_anything_this_feature_commits(
    path: Path,
) -> None:
    """The fixture is not the only place a real record could leak: a docstring example or a test
    string is read by strangers too. Structural checks only -- a denylist of real names would
    itself be personal data, so it stays out of the repository."""
    text = path.read_text(encoding="utf-8")
    domains = set(re.findall(r"(?<![\w/.+:-])[\w.+-]+@([\w-]+(?:\.[\w-]+)+)", text))
    assert domains <= {"example.com"}, (path.name, domains)
    handles = set(re.findall(r"linkedin\.com/in/([\w%.-]+)", text))
    assert handles <= _SYNTHETIC_PROFILE_HANDLES, (path.name, handles)
    for token in re.findall(r"rcm=([A-Za-z0-9]+)", text):
        assert "EXAMPLE" in token.upper() or "TEST" in token.upper(), (path.name, token)
    assert not re.search(r"\+?\d{1,3}[\s.-]\(?\d{2,4}\)?[\s.-]\d{3,4}[\s.-]\d{3,4}", text), (
        path.name
    )


